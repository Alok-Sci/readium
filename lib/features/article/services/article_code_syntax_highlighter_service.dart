  /// Light theme based on VSCode Light
  static final lightTheme = vsTheme;

  /// Dark theme based on VSCode Dark
  static final darkTheme = vs2015Theme;

  /// Returns a Widget for highlighted [code], or null if [language] isn't supported.
  /// Callers should fall back to plain text rendering if null is returned.
  Widget? highlightWidget(
    String code, {
    required String? language,
    required bool isDark,
    TextStyle? baseStyle,
  }) {
    final resolvedLang = _resolveLanguage(language);
    if (resolvedLang == null) return null;

    return HighlightView(
      code,
      language: resolvedLang,
      theme: isDark ? darkTheme : lightTheme,
      padding: EdgeInsets.only(right: 24, left: 24, top: 18, bottom: 8),
      textStyle: baseStyle,
    );
  }

  /// Resolves language aliases to their canonical names
  static String? _resolveLanguage(String? language) {
    if (language == null || language.isEmpty) return null;
    final lower = language.toLowerCase();
    final resolved = _aliases[lower] ?? lower;
    return supportedLanguages.contains(resolved) ? resolved : null;
  }
